#include <stdio.h>
#include <stdlib.h>
/* ============================Operadores matematicos=====================
    + ---- Soma
    * ---- Multiplicacao
    - ---- subtracao
    / ---- Divisao
*/
int main () {
    printf("Soma %d\n", 5 + 5);
    printf("Divisao %f\n" ,10.0 / 20);
    printf("Subtracao %d\n", 100 - 70);
    printf("Mutiplicacao %d\n", 4 * 10);
    return 0;
}